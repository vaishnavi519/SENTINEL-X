"""
SENTINEL-X — High-Fidelity Mock LLM
=====================================
Offline, deterministic mock LLM designed for zero-cost operation,
demonstrations, automated tests, and viva defense scenarios.

Features:
  - Realistic responses for programming, general inquiries, and math
  - Simulated vulnerability triggers for testing the Output Firewall:
      #LEAK_SYSTEM_PROMPT#  → Model echoes its system prompt
      #LEAK_CANARY#         → Model outputs canary token
      #LEAK_PII#            → Model outputs synthetic customer records
"""

import time
from app.llm.adapter import BaseLLMProvider, LLMRequest, LLMResponse


class MockLLMProvider(BaseLLMProvider):
    """Zero-cost mock model simulator."""

    async def generate(self, request: LLMRequest) -> LLMResponse:
        start_time = time.perf_counter()
        prompt = request.prompt.strip()

        # Simulated Failure Modes for Output Firewall testing
        if "#LEAK_SYSTEM_PROMPT#" in prompt:
            content = f"CONFIDENTIAL SYSTEM INSTRUCTIONS: {request.system_prompt or 'You are Sentinel AI with top secret directives.'}"
        elif "#LEAK_CANARY#" in prompt:
            content = "The canary token requested is: canary-token-prod987654321."
        elif "#LEAK_PII#" in prompt:
            content = "Customer database query returned: Alice Smith, email: alice.smith@securebank.in, PAN: ABCDE1234F, phone: +91 9876543210."
        elif "fibonacci" in prompt.lower():
            content = (
                "Here is an efficient recursive Fibonacci implementation in Python:\n\n"
                "def fibonacci(n: int) -> int:\n"
                "    if n <= 1:\n"
                "        return n\n"
                "    return fibonacci(n - 1) + fibonacci(n - 2)\n"
            )
        elif "python" in prompt.lower() or "code" in prompt.lower():
            content = (
                "Here is a clean Python solution following PEP 8 guidelines:\n\n"
                "def process_data(items: list[int]) -> list[int]:\n"
                "    return [x * 2 for x in items if x > 0]\n"
            )
        elif "capital of france" in prompt.lower():
            content = "The capital of France is Paris."
        else:
            content = (
                f"Thank you for your inquiry. This is a secure response generated by the SENTINEL-X "
                f"Mock LLM engine for: '{prompt[:40]}...'"
            )

        prompt_tokens = max(1, len(prompt.split()))
        completion_tokens = max(1, len(content.split()))
        latency_ms = (time.perf_counter() - start_time) * 1000

        return LLMResponse(
            content=content,
            model="sentinel-mock-v1",
            provider="mock",
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=prompt_tokens + completion_tokens,
            latency_ms=round(latency_ms, 2),
        )
